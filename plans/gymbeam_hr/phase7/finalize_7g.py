"""Phase 7G: refresh SUBMISSION_MANIFEST.json and SHA256SUMS.txt of the extracted package after the 7G additions (local, no network).
Every VERIFIED entry must still equal its recorded sha256_dest; AUTHORED entries are re-hashed; files not yet listed are added as AUTHORED;
the stale 7B entry of smoke_tests.py (HASH_MISMATCH_AT_FINALIZE) is turned into an AUTHORED entry with the real hash.
usage: python finalize_7g.py <extracted submission folder>"""
import hashlib, json, sys
from pathlib import Path

SUB = Path(sys.argv[1]).resolve()
sha = lambda p: hashlib.sha256(Path(p).read_bytes()).hexdigest()
man = json.loads((SUB / "SUBMISSION_MANIFEST.json").read_text(encoding="utf-8"))
bad, changed = [], []
for e in man["files"]:
    f = SUB / e["dest"]
    if e["status"] == "VERIFIED":
        if not f.is_file() or sha(f) != e["sha256_dest"]:
            bad.append(e["dest"])
    elif e["status"] in ("AUTHORED", "HASH_MISMATCH_AT_FINALIZE"):
        h = sha(f)
        if e["status"] != "AUTHORED" or e["sha256_dest"] != h:
            changed.append(e["dest"])
        if e["status"] == "HASH_MISMATCH_AT_FINALIZE":
            e.update({"source": None, "role": "authored for this package (or generated by a package script)", "category": "authored", "status": "AUTHORED"})
            for k in ("sha256_source_before", "sha256_source_after", "refreshed_in_7B"):
                e.pop(k, None)
        e["sha256_dest"], e["bytes"] = h, f.stat().st_size
known = {e["dest"] for e in man["files"]}
SKIP = {"SUBMISSION_MANIFEST.json", "SHA256SUMS.txt", ".gitkeep"}
for p in sorted(SUB.rglob("*")):
    rel = p.relative_to(SUB).as_posix()
    if p.is_file() and rel not in known and rel not in SKIP and "__pycache__" not in p.parts:
        man["files"].append({"source": None, "dest": rel, "role": "authored for this package (or generated by a package script)", "category": "authored", "bytes": p.stat().st_size, "sha256_dest": sha(p), "status": "AUTHORED"})
        changed.append(rel + " (new)")
man["summary"] = {"verified_copies": sum(e["status"] == "VERIFIED" for e in man["files"]), "authored": sum(e["status"] == "AUTHORED" for e in man["files"]),
                  "missing_sources": [e["source"] for e in man["files"] if e["status"] == "MISSING_SOURCE"], "hash_problems": bad, "total_files": len([e for e in man["files"] if e["status"] != "MISSING_SOURCE"])}
man["phase_7g"] = "7G refresh: added tools/REPRODUCE_SVE_TRI_OBJAVE_7F.ps1, tools/repro_helper.py, tools/offline_guard, setup/constraints_media_7G.txt and the 7G documents; bootstrap_workspace.py updated (copies the constraints file); every entry re-hashed."
(SUB / "SUBMISSION_MANIFEST.json").write_text(json.dumps(man, indent=1, ensure_ascii=False), encoding="utf-8")
lines = [f"{sha(p)}  {p.relative_to(SUB).as_posix()}" for p in sorted(SUB.rglob("*")) if p.is_file() and p.relative_to(SUB).as_posix() not in {"SHA256SUMS.txt", ".gitkeep"} and "__pycache__" not in p.parts]
with open(SUB / "SHA256SUMS.txt", "w", encoding="utf-8", newline="\n") as fh:
    fh.write("\n".join(lines) + "\n")
print(json.dumps(man["summary"], indent=1)); print("changed/added:", len(changed)); [print("  ", c) for c in changed]
sys.exit(1 if bad else 0)
