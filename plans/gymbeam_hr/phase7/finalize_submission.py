"""Phase 7A: finalize the manifest. Adds the files authored for the package, re-verifies every copied file against its source (SHA-256), writes SHA256SUMS.txt.
Local only. Exit code 1 if anything fails verification."""
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SUB = ROOT / "submission"
sha = lambda p: hashlib.sha256(Path(p).read_bytes()).hexdigest()
man = json.loads((SUB / "SUBMISSION_MANIFEST.json").read_text(encoding="utf-8"))
man["files"] = [e for e in man["files"] if e.get("category") != "authored"]
bad = []
for e in man["files"]:
    if e["status"] != "VERIFIED":
        continue
    d, s = SUB / e["dest"], ROOT / e["source"]
    if not d.is_file() or sha(d) != e["sha256_dest"] or sha(s) != e["sha256_source_before"]:
        bad.append(e["dest"])
        e["status"] = "HASH_MISMATCH_AT_FINALIZE"
known = {e["dest"] for e in man["files"]}
SKIP = {"SUBMISSION_MANIFEST.json", "SHA256SUMS.txt", ".gitkeep"}
for p in sorted(SUB.rglob("*")):
    rel = p.relative_to(SUB).as_posix()
    if p.is_file() and rel not in known and rel not in SKIP:
        man["files"].append({"source": None, "dest": rel, "role": "authored for this package (or generated by a package script)", "category": "authored", "bytes": p.stat().st_size,
                             "sha256_dest": sha(p), "status": "AUTHORED"})
man["summary"] = {"verified_copies": sum(e["status"] == "VERIFIED" for e in man["files"]), "authored": sum(e["status"] == "AUTHORED" for e in man["files"]),
                  "missing_sources": [e["source"] for e in man["files"] if e["status"] == "MISSING_SOURCE"], "hash_problems": bad + [e["source"] for e in man["files"] if e["status"] == "HASH_MISMATCH"],
                  "total_files": len([e for e in man["files"] if e["status"] != "MISSING_SOURCE"])}
(SUB / "SUBMISSION_MANIFEST.json").write_text(json.dumps(man, indent=1, ensure_ascii=False), encoding="utf-8")
lines = []
for p in sorted(SUB.rglob("*")):
    rel = p.relative_to(SUB).as_posix()
    if p.is_file() and rel not in {"SHA256SUMS.txt", ".gitkeep"}:
        lines.append(f"{sha(p)}  {rel}")
with open(SUB / "SHA256SUMS.txt", "w", encoding="utf-8", newline="\n") as fh:   # LF endings so that `sha256sum -c` can read it
    fh.write("\n".join(lines) + "\n")
print(json.dumps(man["summary"], indent=1)); sys.exit(1 if man["summary"]["hash_problems"] else 0)
